import json
import shutil
from pathlib import Path

import pytest

from webhelix.comparison import compare_iteration, compare_run
from webhelix.spec import read_json

ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def saved_run(tmp_path):
    source = ROOT / "examples/scripted/integration"
    run = tmp_path / "run"
    run.mkdir()
    for filename in ["autohelix-history.jsonl", "project-start.json"]:
        shutil.copy2(source / filename, run / filename)
    for i in range(3):
        shutil.copytree(source / f"iteration-{i}", run / "batches" / f"iteration-{i}")
    (run / "autohelix-notes").mkdir()
    (run / "autohelix-notes/iter-1.md").write_text(
        "Recorded note <script>alert(1)</script>"
    )
    return run


def test_comparison_has_provenance_observations_and_safe_html(saved_run, tmp_path):
    out = tmp_path / "comparison"
    result = compare_iteration(ROOT, saved_run, 1, out)
    assert result["before_iteration"] == 0
    assert result["candidate_author"] == "Scripted optimizer (predetermined change)"
    assert result["target_rate_change_from_retained"] == 0
    document = (out / "index.html").read_text()
    assert "<script>alert(1)</script>" not in document
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in document
    assert "this candidate was not generated by an LLM" in document
    assert document.count('sandbox=""') == 2
    assert (out / "before.html").read_text().count('data-product="dock-c"') == 1
    assert (out / "after.html").read_text().count('data-product="dock-c"') == 2
    assert "dock-b" in (out / "after.html").read_text()
    assert (out / "observation.diff").read_text()
    with pytest.raises(FileExistsError):
        compare_iteration(ROOT, saved_run, 1, out)


def test_compare_against_retained_state_skips_rejected_candidate(saved_run, tmp_path):
    rows = [
        json.loads(line)
        for line in (saved_run / "autohelix-history.jsonl").read_text().splitlines()
    ]
    # Counterfactual fixture for selection logic only, not an experimental result.
    rows[1]["accepted"] = False
    (saved_run / "autohelix-history.jsonl").write_text(
        "\n".join(json.dumps(r) for r in rows)
    )
    decision = read_json(saved_run / "batches/iteration-1/acceptance.json")
    decision["autohelix_result"]["accepted"] = False
    (saved_run / "batches/iteration-1/acceptance.json").write_text(json.dumps(decision))
    result = compare_iteration(ROOT, saved_run, 2, tmp_path / "comparison")
    assert result["before_iteration"] == 0
    assert result["hypothesis_source"] == "missing"


def test_saved_candidate_tampering_is_not_rendered_as_evidence(saved_run, tmp_path):
    path = saved_run / "batches/iteration-1/candidate.json"
    path.write_text('{"version":1,"groups":[["dock-a","dock-b","dock-c","dock-d"]]}')
    with pytest.raises(ValueError, match="evaluated bytes"):
        compare_iteration(ROOT, saved_run, 1, tmp_path / "comparison")
    compare_run(ROOT, saved_run)
    assert (saved_run / "comparisons/iter-1/report-error.json").exists()


def test_failed_evaluation_has_no_behavioral_rate_comparison(saved_run, tmp_path):
    # Counterfactual fixture, not an altered experimental report.
    path = saved_run / "batches/iteration-1/report.json"
    report = read_json(path)
    report["metrics"]["evaluation_ok"] = False
    path.write_text(json.dumps(report))
    out = tmp_path / "comparison"
    result = compare_iteration(ROOT, saved_run, 1, out)
    assert result["target_rate_change_from_retained"] is None
    assert result["target_rate_change_from_clean"] is None
    assert "Unmeasured — evaluation failed" in (out / "index.html").read_text()
    assert not result["evaluation_ok"]
